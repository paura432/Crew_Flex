import type { ReactNode } from "react";

export const controlClass =
  "block w-full min-h-10 pointer-coarse:min-h-11 rounded-lg border border-line bg-white px-3 py-2 text-[15px] text-ink placeholder:text-muted aria-[invalid=true]:border-danger";

/** Label + control + hint + error. The control must use `id={id}` and the describedby ids. */
export function Field({
  id,
  label,
  hint,
  error,
  children,
}: {
  id: string;
  label: string;
  hint?: string;
  error?: string;
  children: ReactNode;
}) {
  return (
    <div className="flex flex-col gap-1.5">
      <label htmlFor={id} className="text-sm font-semibold">
        {label}
      </label>
      {children}
      {hint && !error && (
        <p id={`${id}-hint`} className="text-sm text-muted">
          {hint}
        </p>
      )}
      {error && (
        <p id={`${id}-error`} className="text-sm font-medium text-danger">
          {error}
        </p>
      )}
    </div>
  );
}

export function describedBy(id: string, error?: string, hint?: string) {
  return error ? `${id}-error` : hint ? `${id}-hint` : undefined;
}
